function declineRussian(
  count: number,
  one: string,
  few: string,
  many: string,
): string {
  const hundreds = Math.abs(count) % 100;
  const tens = hundreds % 10;
  if (hundreds > 10 && hundreds < 20) return many;
  if (tens > 1 && tens < 5) return few;
  if (tens === 1) return one;
  return many;
}

